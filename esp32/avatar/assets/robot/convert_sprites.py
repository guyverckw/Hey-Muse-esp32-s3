#!/usr/bin/env python3
"""
Convert robot PNG sprites into RGB565 arrays for the ESP32-S3.

Input:
    idle_01.png
    idle_02.png
    blink_01.png

Output:
    robot_sprites.h

Each image must be 64x64 pixels.
Transparent pixels are converted to black for the
first AMOLED avatar-rendering prototype.
"""

from pathlib import Path
from PIL import Image

# Directory containing this script and the PNG files
ROOT = Path(__file__).resolve().parent

SPRITES = [
    "idle_01",
    "idle_02",
    "idle_experiment_01",
    "idle_experiment_02",
    "idle_experiment_03",
    "idle_experiment_04",
    "idle_experiment_05",
    "idle_experiment_06",
    "blink_01",
    "listening_v8_01",
    "listening_v8_02",
    "listening_v8_03",
    "listening_v8_04",
    "listening_v8_05",
    "listening_v8_06",
    "listening_01",
    "listening_02",
    "thinking_v8_01",
    "thinking_v8_02",
    "thinking_v8_03",
    "thinking_v8_04",
    "thinking_v8_05",
    "thinking_v8_06",
    "thinking_01",
    "thinking_02",
    "speaking_01",
    "speaking_02",
    "speaking_03",
    "happy_01",
    "happy_02",
    "boot_01",
    "boot_02",
    "boot_03",
    "error_01",
    "error_02",
    "poweroff_01",
    "poweroff_02",
    "sleep_01",
    "sleep_02",
]

WIDTH = 64
HEIGHT = 64

OUTPUT = ROOT / "robot_sprites.h"


def rgba_to_rgb565(r, g, b, a):
    """Convert an RGBA pixel to RGB565."""

    # Composite partially transparent pixels onto black.
    r = (r * a + 127) // 255
    g = (g * a + 127) // 255
    b = (b * a + 127) // 255

    return (
        ((r >> 3) << 11)
        | ((g >> 2) << 5)
        | (b >> 3)
    )


def convert_sprite(name):
    """Load a PNG and return its RGB565 pixels."""

    path = ROOT / f"{name}.png"

    if not path.exists():
        raise FileNotFoundError(f"Missing sprite: {path}")

    with Image.open(path) as source:
        image = source.convert("RGBA")

    if image.size != (WIDTH, HEIGHT):
        raise ValueError(
            f"{name}: Expected {WIDTH}x{HEIGHT}, "
            f"but found {image.width}x{image.height}"
        )

    pixels = [
        rgba_to_rgb565(r, g, b, a)
        for r, g, b, a in image.get_flattened_data()
    ]

    print(f"Converted {name}: {len(pixels)} pixels")

    return pixels


def main():
    # Convert every sprite before writing the output.
    # This avoids creating a partial header if an input is invalid.
    converted = {
        name: convert_sprite(name)
        for name in SPRITES
    }

    with OUTPUT.open("w", encoding="utf-8") as out:
        out.write("// Auto-generated by convert_sprites.py\n")
        out.write("// RGB565 format, transparent pixels over black\n")
        out.write("#pragma once\n")
        out.write("#include <stdint.h>\n\n")

        out.write(f"#define ROBOT_SPRITE_W {WIDTH}\n")
        out.write(f"#define ROBOT_SPRITE_H {HEIGHT}\n\n")

        for name, pixels in converted.items():
            out.write(
                f"static const uint16_t "
                f"robot_{name}[{WIDTH * HEIGHT}] = {{\n"
            )

            for i in range(0, len(pixels), 16):
                row = pixels[i:i + 16]

                values = ", ".join(
                    f"0x{pixel:04X}"
                    for pixel in row
                )

                out.write(f"    {values},\n")

            out.write("};\n\n")

    print()
    print("SUCCESS: All sprites converted")
    print(f"Header created: {OUTPUT}")
    print(
        f"Raw sprite data: "
        f"{len(SPRITES) * WIDTH * HEIGHT * 2:,} bytes"
    )


if __name__ == "__main__":
    main()
